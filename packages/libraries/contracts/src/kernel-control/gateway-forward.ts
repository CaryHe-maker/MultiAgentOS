import { Type, type Static, type TSchema } from 'typebox';
import {
  ReportSessionCommandRequestSchema,
  ReportSessionListRequestSchema,
} from '../kernel-unit/session-replies.js';
import {
  CloseRunRequestSchema,
  EndAgentRunRequestSchema,
  ReadProjectFileRequestSchema,
  RegisterAgentRunRequestSchema,
  RequestHumanRequestSchema,
  SubmitUnitRequestSchema,
} from '../kernel-unit/workflow-syscalls.js';
import { IdSchemas } from '../platform-common/ids.js';
import { closed } from '../platform-common/schema-helpers.js';
import {
  AnswerAuthorizationRequestSchema,
  AnswerHumanRequestSchema,
  ReadArtifactRequestSchema,
  ShutdownRequestSchema,
} from './interaction-requests.js';
import {
  DeleteSessionRequestSchema,
  ListSessionsRequestSchema,
  OpenSessionRequestSchema,
  StartRunRequestSchema,
  StartSessionRequestSchema,
} from './session-requests.js';
import { CloseReasonSchema } from './run-outcome.js';

const forward = <C extends string, R extends string, S extends TSchema>(
  caller: C,
  requestType: R,
  request: S,
) => closed({ caller: Type.Literal(caller), requestType: Type.Literal(requestType), request });

/** What Gateway hands to Core; `sessionId` is generated by Gateway on a new Session. */
export const GatewayForwardSchema = Type.Union(
  [
    forward('workflow', 'registerAgentRun', RegisterAgentRunRequestSchema),
    forward('workflow', 'submitUnit', SubmitUnitRequestSchema),
    forward('workflow', 'endAgentRun', EndAgentRunRequestSchema),
    forward('workflow', 'closeRun', CloseRunRequestSchema),
    forward('workflow', 'requestHuman', RequestHumanRequestSchema),
    forward('workflow', 'readProjectFile', ReadProjectFileRequestSchema),
    forward('workflow', 'reportSessionCommand', ReportSessionCommandRequestSchema),
    forward('workflow', 'reportSessionList', ReportSessionListRequestSchema),
    closed({
      caller: Type.Literal('user-interaction'),
      requestType: Type.Literal('startSession'),
      request: StartSessionRequestSchema,
      sessionId: IdSchemas.sessionId,
    }),
    closed({
      caller: Type.Literal('user-interaction'),
      requestType: Type.Literal('startRun'),
      request: StartRunRequestSchema,
      sessionId: IdSchemas.sessionId,
    }),
    forward('user-interaction', 'openSession', OpenSessionRequestSchema),
    forward('user-interaction', 'listSessions', ListSessionsRequestSchema),
    forward('user-interaction', 'deleteSession', DeleteSessionRequestSchema),
    forward('user-interaction', 'answerAuthorization', AnswerAuthorizationRequestSchema),
    forward('user-interaction', 'answerHuman', AnswerHumanRequestSchema),
    forward('user-interaction', 'readArtifact', ReadArtifactRequestSchema),
    forward('user-interaction', 'shutdown', ShutdownRequestSchema),
  ],
  { $id: 'kernel.control.GatewayForward.v1' },
);
export type GatewayForward = Static<typeof GatewayForwardSchema>;
export type GatewayRequestType = GatewayForward['requestType'];

/**
 * Pushed by Core for each run; Gateway only reads it (Kernel/Gateway 4). `sessionId` lets Gateway
 * check that a request names the run's own Session.
 */
export const AdmissionProjectionSchema = Type.Union(
  [
    closed({
      workflowRunId: IdSchemas.workflowRunId,
      sessionId: IdSchemas.sessionId,
      runState: Type.Literal('RUNNING'),
    }),
    closed({
      workflowRunId: IdSchemas.workflowRunId,
      sessionId: IdSchemas.sessionId,
      runState: Type.Enum(['CONVERGING', 'CLOSED']),
      closeReason: CloseReasonSchema,
    }),
  ],
  { $id: 'kernel.control.AdmissionProjection.v1' },
);
export type AdmissionProjection = Static<typeof AdmissionProjectionSchema>;

/** Pushed by Core when a Session opens or closes, for the `SESSION_NOT_FOUND` check (Kernel/Gateway 3). */
export const SessionProjectionSchema = closed(
  { sessionId: IdSchemas.sessionId, state: Type.Enum(['OPEN', 'CLOSED']) },
  'kernel.control.SessionProjection.v1',
);
export type SessionProjection = Static<typeof SessionProjectionSchema>;
